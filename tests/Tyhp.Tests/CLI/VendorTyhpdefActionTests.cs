    }

    private static string AddInstalledPackage(
        string projectDir,
        string name,
        string version,
        bool php,
        bool autoload = true,
        bool hasTyhpPackage = false)
    {
        var slash = name.IndexOf('/');
        var vendor = name[..slash];
        var pkg = name[(slash + 1)..];
        var install = Path.Combine(projectDir, "vendor", vendor, pkg);
        Directory.CreateDirectory(install);
        var autoloadJson = autoload
            ? """{"psr-4":{"Acme\\":"src/"}}"""
            : "{}";
        File.WriteAllText(
            Path.Combine(install, "composer.json"),
            "{\"name\":\"" + name + "\",\"version\":\"" + version + "\",\"autoload\":" + autoloadJson
            + (hasTyhpPackage
                ? ",\"extra\":{\"tyhp\":{\"package\":{}}}"
                : "")
            + "}");
        if (php)
        {
            var src = Path.Combine(install, "src");
            Directory.CreateDirectory(src);
            File.WriteAllText(src + "/Widget.php", "<?php\nnamespace Acme;\nclass Widget { public function ping(): int { return 1; } }\n");
        }

        var relativeInstall = "../" + vendor + "/" + pkg;
        var existingPath = Path.Combine(projectDir, "vendor", "composer", "installed.json");
        var packages = new JsonArray();
        if (File.Exists(existingPath))
        {
            try
            {
                var root = JsonNode.Parse(File.ReadAllText(existingPath))?.AsObject();
                if (root?["packages"] is JsonArray existing)
                {
                    foreach (var item in existing)
                    {
                        if (item is not null)
                        {
                            packages.Add(item.DeepClone());
                        }
                    }
                }
            }
            catch (Exception)
            {
            }
        }

        packages.Add(new JsonObject
        {
            ["name"] = name,
            ["version"] = version,
            ["type"] = "library",
            ["install-path"] = relativeInstall,
        });
        var installed = new JsonObject
        {
            ["packages"] = packages,
            ["dev"] = true,
        };
        File.WriteAllText(existingPath, installed.ToJsonString() + Environment.NewLine);
        return install;
    }

    public void Dispose()
    {
        Environment.ExitCode = this._previousExitCode;
        foreach (var directory in this._tempDirectories)
        {
            try
            {
                if (Directory.Exists(directory))
                {
                    Directory.Delete(directory, recursive: true);
                }
            }
            catch (IOException)
            {
            }
        }
    }

    private sealed class FakeCompanionProbe : ICompanionPackageProbe
    {
        public Dictionary<string, string> Available { get; } = new(StringComparer.OrdinalIgnoreCase);

        public int FetchCount { get; private set; }

        public bool TryResolve(string companionPackageName, string? upstreamVersion, string projectRoot, out string constraint)
        {
            this.FetchCount++;
            if (this.Available.TryGetValue(companionPackageName, out constraint!))
            {
                return true;
            }

            constraint = "";
            return false;
        }
    }

    private sealed class RecordingComposerRunner : IComposerCommandRunner
    {
        public List<(bool Dev, bool NoScripts, List<string> Packages)> Batches { get; } = [];

        public bool ThrowIfCalled { get; init; }

        public Action<string, IReadOnlyList<string>>? AfterRequire { get; init; }

        public ComposerCommandResult Run(
            string projectRoot,
            IReadOnlyList<string> arguments,
            IReadOnlyDictionary<string, string>? extraEnvironment)
        {
            if (this.ThrowIfCalled)
            {
                throw new InvalidOperationException("Composer must not run");
            }

            extraEnvironment.Should().NotBeNull();
            extraEnvironment!.Should().ContainKey(VendorTyhpdefLayout.VendorRunningEnvironmentVariable);
            var dev = arguments.Contains("--dev");
            var noScripts = arguments.Contains("--no-scripts");
            var packages = arguments.Where(a => a.Contains(':', StringComparison.Ordinal) && !a.StartsWith("--")).ToList();
            this.Batches.Add((dev, noScripts, packages));
            this.AfterRequire?.Invoke(projectRoot, arguments);
            return new ComposerCommandResult(0, "", "");
        }
    }
