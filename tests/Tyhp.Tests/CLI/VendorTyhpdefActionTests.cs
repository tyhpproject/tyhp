    private GenerateTyhpdefAction RunVendor(
        string projectDir,
        ICompanionPackageProbe probe,
        IComposerCommandRunner runner,
        IReadOnlySet<string>? phpExtCatalog = null,
        Action<TyhpdefGenerationOptions, TyhpdefGenerationResult, CancellationToken>? extensionHook = null,
        Func<string, string?>? readEnv = null,
        bool overwrite = false)
    {
        var settings = new Dictionary<string, string?>
        {
            ["*project_file_path"] = Path.Combine(projectDir, "tyhp.json"),
            ["vendor"] = "true",
            ["quiet"] = "true",
            ["overwrite"] = overwrite ? "true" : "false",
            ["no-docs"] = "true",
        };
        var project = new Project(new ConfigurationBuilder().AddInMemoryCollection(settings).Build());
        Environment.ExitCode = (int)ExitCode.Success;
        var action = new GenerateTyhpdefAction(project)
        {
            VendorGenerator = new VendorTyhpdefGenerator
            {
                CompanionProbe = probe,
                ComposerRunner = runner,
                FirstPartyPhpExtensions = phpExtCatalog ?? new HashSet<string>(StringComparer.OrdinalIgnoreCase),
                ExtensionGenerateHook = extensionHook,
                ReadEnvironment = readEnv ?? (_ => null),
                AlwaysPresentExtensions = _ => VendorTyhpdefLayout.AlwaysPresentPhpExtensions,
            },
        };
        action.Start(CancellationToken.None);
        return action;
    }

    private ComposerAction CreateComposerAction(
        string projectDir,
        string[] composerArgs,
        VendorTyhpdefGenerator? vendorGenerator = null,
        bool noTyhpdef = false,
        Func<string, string?>? readEnv = null)
    {
        var settings = new Dictionary<string, string?>
        {
            ["*project_file_path"] = Path.Combine(projectDir, "tyhp.json"),
            ["quiet"] = "true",
            ["no-tyhpdef"] = noTyhpdef ? "true" : "false",
        };
        var project = new Project(new ConfigurationBuilder().AddInMemoryCollection(settings).Build());
        Environment.ExitCode = (int)ExitCode.Success;
        return new ComposerAction(project)
        {
            Args = composerArgs,
            FindPhp = () => "/usr/bin/php",
            ResolveComposer = _ => "/usr/bin/composer",
            RunComposerProcess = (_, _, _) => 0,
            VendorGenerator = vendorGenerator,
            ReadEnvironment = readEnv ?? (_ => null),
        };
    }

