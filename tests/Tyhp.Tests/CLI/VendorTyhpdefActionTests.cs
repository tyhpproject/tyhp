    [Fact]
    public void Layout_StampInsertsLockedHeader()
    {
        var stamped = VendorTyhpdefLayout.ApplyHeader("<?tyhpdef\nclass Demo {}\n", "acme/widget@1.0.0");
        stamped.Should().Contain("// Generated by `tyhp generate_tyhpdef --vendor`. Do not edit this file.");
        stamped.Should().Contain("not in vendor-tyhpdef/");
        stamped.Should().Contain("// @vendor-identity: acme/widget@1.0.0");
        stamped.Should().StartWith("<?tyhpdef\n");

        var path = Path.Combine(Path.GetTempPath(), "tyhp-vendor-stamp-" + Guid.NewGuid().ToString("N") + ".tyhpdef");
        File.WriteAllText(path, stamped);
        try
        {
            VendorTyhpdefLayout.FileHasMatchingIdentity(path, "acme/widget@1.0.0").Should().BeTrue();
            VendorTyhpdefLayout.FileHasMatchingIdentity(path, "acme/widget@9.9.9").Should().BeFalse();
        }
        finally
        {
            File.Delete(path);
        }
    }

