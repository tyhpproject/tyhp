    private static void WriteComposerJson(
        string projectDir,
        Dictionary<string, string>? require = null,
        Dictionary<string, string>? requireDev = null,
        IReadOnlyList<string>? repositories = null)
    {
        require ??= new Dictionary<string, string> { ["php"] = ">=8.2" };
        var requireJson = string.Join(",", require.Select(kv => $"\"{kv.Key}\": \"{kv.Value}\""));
        var requireDevJson = requireDev is { Count: > 0 }
            ? ",\"require-dev\": {" + string.Join(",", requireDev.Select(kv => $"\"{kv.Key}\": \"{kv.Value}\"")) + "}"
            : "";
        var reposJson = repositories is { Count: > 0 }
            ? ",\"repositories\": [" + string.Join(",", repositories) + "]"
            : "";
        File.WriteAllText(
            Path.Combine(projectDir, "composer.json"),
            "{\"name\":\"app/tyhp-project\",\"require\":{" + requireJson + "}" + requireDevJson + reposJson + "}");
    }

