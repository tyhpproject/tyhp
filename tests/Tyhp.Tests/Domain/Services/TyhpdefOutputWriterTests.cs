    [Fact]
    public void Write_FormatsStructsTypeAliasesPartialAndClassAlias()
    {
        var file = new TyhpdefFile
        {
            TypeAliases =
            [
                new TyhpdefTypeAlias
                {
                    Name = "JsonMap",
                    AliasedType = "array<string, mixed>",
                    GenericParameters = [],
                },
            ],
            GlobalTypes =
            [
                new TyhpdefClassDeclaration
                {
                    Kind = "struct",
                    Name = "CallableArgs1",
                    GenericParameters = [new TyhpdefGenericParameter { Name = "T1" }],
                    Properties = [new TyhpdefProperty { Name = "0 as $_1", Type = "T1" }],
                },
                new TyhpdefClassDeclaration
                {
                    Kind = "class",
                    Name = "DateTime",
                    AsAlias = "DateTimeImmutable",
                    IsPartial = true,
                },
                new TyhpdefClassDeclaration
                {
                    Kind = "class",
                    Name = "Some\\Namespaced\\OldName",
                    AsAlias = "NewName",
                },
            ],
        };

        var output = TyhpdefOutputWriter.Write(file);

        output.Should().Contain("type JsonMap = array<string, mixed>;");
        output.Should().Contain("type CallableArgs1<T1> = struct {");
        output.Should().Contain("T1 0 as $_1;");
        output.Should().Contain("partial class DateTime as DateTimeImmutable {");
        // `class PhpName as TyhpName`: PhpName is the FQN-capable `AliasOf=className` side and
        // must be backslash-qualified; TyhpName binds to a bare T_STRING and must not be.
        output.Should().Contain("class \\Some\\Namespaced\\OldName as NewName {");
        AssertParses(output);
    }

