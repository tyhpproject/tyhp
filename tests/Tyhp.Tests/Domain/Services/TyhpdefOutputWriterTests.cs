        };

    private static void AssertDecorationOrder(string output, string docSnippet, string phpGate, string attribute, string declaration)
    {
        var doc = output.IndexOf(docSnippet, StringComparison.Ordinal);
        doc.Should().BeGreaterThanOrEqualTo(0, "missing doc snippet {0} in:\n{1}", docSnippet, output);

        var gate = output.IndexOf(phpGate, doc, StringComparison.Ordinal);
        gate.Should().BeGreaterThan(doc, "PHP gate should follow the docblock in:\n{0}", output);

        var attr = output.IndexOf(attribute, gate, StringComparison.Ordinal);
        attr.Should().BeGreaterThan(gate, "attribute should follow the PHP gate in:\n{0}", output);

        var decl = output.IndexOf(declaration, attr, StringComparison.Ordinal);
        decl.Should().BeGreaterThan(attr, "declaration should follow attributes in:\n{0}", output);
    }

    [Fact]
    public void Write_FormatsNestedExtensionGroupsAndByRefReceiver()
    {
        var file = new TyhpdefFile
        {
            GlobalTypes =
            [
                new TyhpdefClassDeclaration
                {
                    Kind = "extension",
                    Name = "ArrayExtensions",
                    ExtensionGroups =
                    [
                        new TyhpdefExtensionGroup
                        {
                            TargetType = "array<TKey, TValue>",
                            GenericParameters =
                            [
                                new TyhpdefGenericParameter { Name = "TKey", Constraint = "int|string" },
                                new TyhpdefGenericParameter { Name = "TValue" },
                            ],
                            Members =
                            [
                                new TyhpdefExtensionMember
                                {
                                    Kind = "fn",
                                    Name = "sort",
                                    ByRefReceiver = true,
                                    Parameters = [new TyhpdefParameter { Name = "flags", Type = "int" }],
                                    ReturnType = "bool",
                                    Body = "\\sort($this, $flags)",
                                },
                            ],
                        },
                    ],
                },
            ],
        };

        var output = TyhpdefOutputWriter.Write(file);

        output.Should().Contain("extension ArrayExtensions {");
        output.Should().Contain("extends<TKey extends int|string, TValue> array<TKey, TValue> {");
        output.Should().Contain("fn sort(&$this, int $flags): bool => \\sort($this, $flags);");
        output.Should().NotContain("extends array");
        AssertParses(output);
    }

    private static void AssertParses(string tyhpdef)
    {
        var result = ParserTestHelper.ParseTyhpdefContent(tyhpdef);
        result.Diagnostics.Errors.Should().BeEmpty(
            string.Join("; ", result.Diagnostics.Errors.Select(e => $"{e.Code} ({e.Line}:{e.Column}): {e.Message}"))
            + "\n--- generated ---\n" + tyhpdef);
        result.Ast.Should().NotBeNull();
    }
