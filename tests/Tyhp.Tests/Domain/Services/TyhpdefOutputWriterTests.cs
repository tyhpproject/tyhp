    [Fact]
    public void Write_FormatsConstantsFunctionsAndTypes()
    {
        var file = new TyhpdefFile
        {
            GlobalConstants =
            [
                new TyhpdefConstant { Name = "JSON_HEX_TAG", Type = "int" },
                new TyhpdefConstant { Name = "IMPORTED", Type = "int", Value = "0", UsesCoalesce = true },
            ],
            GlobalFunctions =
            [
                new TyhpdefFunction
                {
                    Name = "json_encode",
                    Parameters =
                    [
                        new TyhpdefParameter { Name = "value", Type = "mixed" },
                        new TyhpdefParameter { Name = "flags", Type = "int", DefaultValue = "0" },
                    ],
                    ReturnType = "string|false",
                },
            ],
            GlobalTypes =
            [
                new TyhpdefClassDeclaration
                {
                    Kind = "class",
                    Name = "JsonException",
                    Extends = "\\Exception",
                    Implements = ["\\Throwable", "\\Stringable"],
                    Constants = [new TyhpdefConstant { Name = "CODE", Type = "int", Modifiers = ["public"] }],
                    Properties =
                    [
                        new TyhpdefProperty { Name = "message", Type = "string", Modifiers = ["protected"] },
                    ],
                    Methods =
                    [
                        new TyhpdefMethod
                        {
                            Name = "__construct",
                            Modifiers = ["public"],
                            Parameters = [new TyhpdefParameter { Name = "message", Type = "string", DefaultValue = "\"\"" }],
                            ReturnType = "void",
                        },
                    ],
                },
                new TyhpdefClassDeclaration
                {
                    Kind = "interface",
                    Name = "JsonSerializable",
                    Methods =
                    [
                        new TyhpdefMethod { Name = "jsonSerialize", Modifiers = ["public"], ReturnType = "mixed" },
                    ],
                },
                new TyhpdefClassDeclaration
                {
                    Kind = "trait",
                    Name = "JsonHelpers",
                    Methods =
                    [
                        new TyhpdefMethod { Name = "toJson", Modifiers = ["public"], ReturnType = "string" },
                    ],
                },
                new TyhpdefClassDeclaration
                {
                    Kind = "enum",
                    Name = "Status",
                    BackingType = "string",
                    EnumCases =
                    [
                        new TyhpdefEnumCase { Name = "Active", BackingValue = "'active'" },
                        new TyhpdefEnumCase { Name = "Inactive", BackingValue = "'inactive'" },
                    ],
                    Methods =
                    [
                        new TyhpdefMethod { Name = "label", Modifiers = ["public"], ReturnType = "string" },
                    ],
                },
            ],
        };

        var output = TyhpdefOutputWriter.Write(file);

        output.Should().Contain("const int JSON_HEX_TAG;");
        output.Should().Contain("const int IMPORTED ?? 0;");
        output.Should().Contain("function json_encode(mixed $value, int $flags = 0): string|false;");
        output.Should().Contain("class JsonException extends \\Exception implements \\Throwable, \\Stringable {");
        output.Should().Contain("public const int CODE;");
        output.Should().Contain("protected string $message;");
        output.Should().Contain("public function __construct(string $message = \"\"): void;");
        output.Should().Contain("interface JsonSerializable {");
        output.Should().Contain("public function jsonSerialize(): mixed;");
        output.Should().Contain("trait JsonHelpers {");
        output.Should().Contain("enum Status: string {");
        output.Should().Contain("case Active = 'active';");
        output.Should().Contain("case Inactive = 'inactive';");
        AssertParses(output);
    }

