    private static IEnumerable<string> GrammarReservedTypeNameSpellings()
    {
        var grammarDir = Path.Combine(
            TestFileManager.GetRepoRoot(),
            "Tyhp",
            "TyhpLang",
            "Grammar");
        // reservedNonModifiersBase / semiReservedBase are PHP rules shared via
        // `// #include` (see shared/PhpParser.reached.g4); PhpParser.g4 itself
        // only keeps the rules the tyhpdef closure does not reach.
        var grammar = File.ReadAllText(Path.Combine(grammarDir, "PhpParser.g4"))
            + File.ReadAllText(Path.Combine(grammarDir, "shared", "PhpParser.reached.g4"));
        var tokens = ExtractRuleTokens(grammar, "reservedNonModifiersBase")
            .Concat(ExtractRuleTokens(grammar, "semiReservedBase"))
            .Distinct(StringComparer.Ordinal);
        foreach (var token in tokens)
        {
            foreach (var spelling in SpellingsForGrammarToken(token))
            {
                yield return spelling;
            }
        }
    }

    private static IReadOnlyList<string> ExtractRuleTokens(string grammar, string ruleName)
    {
        var needle = "\n" + ruleName + "\n";
        var start = grammar.IndexOf(needle, StringComparison.Ordinal);
        start.Should().BeGreaterThanOrEqualTo(0, "missing grammar rule {0}", ruleName);
        var bodyStart = start + needle.Length;
        var endMatch = Regex.Match(grammar[bodyStart..], @"\n[ \t]*;");
        endMatch.Success.Should().BeTrue("unterminated grammar rule {0}", ruleName);
        var body = grammar.Substring(bodyStart, endMatch.Index);
        var matches = Regex.Matches(body, @"TokenValue=T_([A-Z0-9_]+)");
        matches.Count.Should().BeGreaterThan(0, "no tokens in grammar rule {0}", ruleName);
        return matches.Select(match => match.Groups[1].Value).ToList();
    }

    /// <summary>
    /// Token-name → source spelling. Underscored <c>T_INCLUDE_ONCE</c> names lowercased;
    /// only tokens whose lexer spelling is not the token name need exceptions
    /// (<c>T_LOGICAL_OR</c> is <c>or</c>, magic constants, <c>T_EXIT</c> is <c>exit</c>/<c>die</c>).
    /// </summary>
    private static IReadOnlyList<string> SpellingsForGrammarToken(string tokenName)
        => tokenName switch
        {
            "LOGICAL_OR" => ["or"],
            "LOGICAL_AND" => ["and"],
            "LOGICAL_XOR" => ["xor"],
            "EXIT" => ["exit", "die"],
            "CLASS_C" => ["__CLASS__"],
            "TRAIT_C" => ["__TRAIT__"],
            "FUNC_C" => ["__FUNCTION__"],
