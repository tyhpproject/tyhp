    [Fact]
    public void Write_IncludesDocCommentsWhenEnabledAndOmitsWhenDisabled()
    {
        var file = new TyhpdefFile
        {
            GlobalFunctions =
            [
                new TyhpdefFunction
                {
                    Name = "strlen",
                    DocComment = "Returns the length of a string.",
                    Parameters = [new TyhpdefParameter { Name = "string", Type = "string" }],
                    ReturnType = "int",
                },
            ],
            GlobalTypes =
            [
                new TyhpdefClassDeclaration
                {
                    Kind = "class",
                    Name = "Widget",
                    DocComment = "/**\n * A widget.\n */",
                },
            ],
        };

        var withDocs = TyhpdefOutputWriter.Write(file, includeDocComments: true);
        withDocs.Should().Contain("Returns the length of a string.");
        withDocs.Should().Contain("A widget.");
        AssertParses(withDocs);

        var withoutDocs = TyhpdefOutputWriter.Write(file, includeDocComments: false);
        withoutDocs.Should().NotContain("Returns the length of a string.");
        withoutDocs.Should().NotContain("A widget.");
        withoutDocs.Should().Contain("function strlen(string $string): int;");
        AssertParses(withoutDocs);
    }

