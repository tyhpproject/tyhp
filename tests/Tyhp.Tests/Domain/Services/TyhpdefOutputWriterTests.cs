    [Fact]
    public void FormatDeclaredTypeName_PrefixesEveryReservedNonModifiersAndSemiReservedSpelling()
    {
        var spellings = GrammarReservedTypeNameSpellings().ToList();
        spellings.Should().Contain("isset");
        spellings.Should().Contain("extends");
        spellings.Should().Contain("implements");
        spellings.Should().Contain("include_once");
        spellings.Should().Contain("require_once");
        spellings.Should().Contain("endswitch");
        spellings.Count.Should().BeGreaterThan(50);

        foreach (var spelling in spellings)
        {
            TyhpdefOutputWriter.IsTyhpdefKeywordTypeName(spelling).Should().BeTrue(
                "lexer must treat '{0}' as a non-T_STRING class name", spelling);
            TyhpdefOutputWriter.FormatDeclaredTypeName(spelling, "Ns")
                .Should().Be("\\Ns\\" + spelling, spelling);
        }

        TyhpdefOutputWriter.FormatDeclaredTypeName("Widget", "Ns").Should().Be("Widget");
        TyhpdefOutputWriter.IsTyhpdefKeywordTypeName("is").Should().BeTrue();
        TyhpdefOutputWriter.IsTyhpdefKeywordTypeName("Widget").Should().BeFalse();
    }

