    [Fact]
    public void Write_FormatsClassBodyExtensionMembersAndOperators()
    {
        var file = new TyhpdefFile
        {
            GlobalTypes =
            [
                new TyhpdefClassDeclaration
                {
                    Kind = "class",
                    Name = "Money",
                    Operators =
                    [
                        new TyhpdefMethod
                        {
                            Name = "+",
                            Parameters =
                            [
                                new TyhpdefParameter { Name = "left", Type = "self" },
                                new TyhpdefParameter { Name = "right", Type = "self" },
                            ],
                            ReturnType = "self",
                        },
                    ],
                    ExtensionMembers =
                    [
                        new TyhpdefExtensionMember
                        {
                            Kind = "fn",
                            Name = "formatCurrency",
                            Parameters = [new TyhpdefParameter { Name = "locale", Type = "string", DefaultValue = "'en_US'" }],
                            ReturnType = "string",
                            Body = "$locale",
                        },
                        new TyhpdefExtensionMember
                        {
                            Kind = "fn",
                            Name = "shortLabel",
                            ReturnType = "string",
                            Body = "$this->formatCurrency()",
                        },
                        new TyhpdefExtensionMember
                        {
                            Kind = "operator",
                            Name = "+",
                            Parameters =
                            [
                                new TyhpdefParameter { Name = "left", Type = "self" },
                                new TyhpdefParameter { Name = "right", Type = "self" },
                            ],
                            ReturnType = "self",
                            Body = "$left",
                        },
                    ],
                },
            ],
        };

        var output = TyhpdefOutputWriter.Write(file);

        output.Should().Contain("operator +(self $left, self $right): self;");
        output.Should().Contain("extension fn formatCurrency(string $locale = 'en_US'): string => $locale;");
        output.Should().Contain("extension fn shortLabel(): string => $this->formatCurrency();");
        output.Should().Contain("extension operator +(self $left, self $right): self => $left;");
        output.Should().NotContain("#[\\Tyhp\\Optimize\\Inline]");
        output.Should().NotContain("extension function ");
        AssertParses(output);
    }

